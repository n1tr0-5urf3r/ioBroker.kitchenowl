/**
 * Matches a leading emoji, which KitchenOwl's category names almost always carry.
 *
 * `RGI_Emoji` matches a whole sequence rather than its first character, which
 * matters more than it looks: a skin tone, a flag and a ZWJ sequence are each
 * several code points, and taking only the first turns 👩🏽‍🍳 into 👩 — a
 * different picture, with the cook and the skin the user chose dropped.
 */
const LEADING_EMOJI = /^\s*(\p{RGI_Emoji})/v;

/**
 * An emoji standing in for an item's icon.
 *
 * Falls back to the leading emoji of the item's category, which KitchenOwl
 * users set themselves and which covers items carrying no icon at all, and
 * finally to an empty string rather than a placeholder that would render as a
 * broken image.
 *
 * @param iconKey - Icon key as the API returned it, if any
 * @param categoryName - Name of the item's category, if any
 */
export function itemEmoji(iconKey: string | null | undefined, categoryName?: string | null): string {
	if (iconKey) {
		const mapped = ITEM_EMOJI[iconKey.replace(/-/g, '_').toLowerCase()];
		if (mapped) {
			return mapped;
		}
	}
	return categoryName?.match(LEADING_EMOJI)?.[1] ?? '';
}
